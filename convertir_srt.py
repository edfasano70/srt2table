def convert():
    in_file = input_path.get()
    out_file = output_path.get()
    out_format = output_format.get()
    proj_name = project_name_var.get()

    if not in_file or not out_file:
        messagebox.showerror("Error", "Please specify input and output files.")
        return

    try:
        status_label.config(text=f"Converting to {out_format.upper()}...")
        root.update_idletasks()

        if out_format == "csv":
            convert_srt_to_csv(in_file, out_file)
        elif out_format == "docx":
            try:
                import docx
            except ImportError:
                messagebox.showerror("Missing Dependency", "To export to DOCX, you need to install the 'python-docx' library.\n\nRun in your terminal:\npip install python-docx")
                status_label.config(text="Error: 'python-docx' is not installed.")
                return
            convert_srt_to_docx(in_file, out_file, proj_name)

        messagebox.showinfo("Success", f"Conversion complete!\nFile saved at:\n{out_file}")
        status_label.config(text="Conversion complete!")
    except FileNotFoundError:
        messagebox.showerror("Error", f"Could not find the input file:\n{in_file}")
        status_label.config(text="Error: File not found.")
    except Exception as e:
        messagebox.showerror("Error", f"An unexpected error occurred:\n{e}")
        status_label.config(text=f"Error: {e}")

    save_config()

def save_config():
    """Saves the current configuration to the .ini file."""
    if "DEFAULT" not in config:
        config["DEFAULT"] = {}
    config["DEFAULT"]["last_project_name"] = project_name_var.get()
    config["DEFAULT"]["last_input_path"] = input_path.get()
    config["DEFAULT"]["last_output_path"] = output_path.get()
    config["DEFAULT"]["last_output_format"] = output_format.get()
    with open(config_file_path, "w") as config_file:
        config.write(config_file)

def on_closing():
    """Handles window closing, saving the configuration."""
    save_config()
    root.destroy()


