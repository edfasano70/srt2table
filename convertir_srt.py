# --- The main conversion logic is maintained, but is now called by the GUI ---
def convert_srt_to_csv(srt_path, csv_path, update_callback=None):
    """
    Converts an SRT subtitle file to a CSV file with specific columns.

    Args:
    srt_path (str): The path to the input SRT file.
    csv_path (str): The path for the output CSV file.
    """
    encoding = detect_encoding(srt_path)

    with open(srt_path, 'r', encoding=encoding) as srt_file, \
            open(csv_path, 'w', newline='', encoding='utf-8') as csv_file:

        csv_writer = csv.writer(csv_file)

        # Write the header row
        header = ['Start', 'Arrow', 'End', 'Character', 'Dialogue']
        csv_writer.writerow(header)

        # Read the entire file and split it into subtitle blocks.
        content = srt_file.read()
        subtitle_blocks = re.split(r'\n\n+', remove_invalid_xml_chars(content).strip())

        for block in subtitle_blocks:
            lines = block.strip().split('\n')
            if len(lines) < 2:
                continue  # Skip incorrectly formatted blocks

            # Columns 1, 2, and 3: Timecodes and arrow
            time_line = lines[1]
            try:
                full_start_time, full_end_time = time_line.split(' --> ')
                # Get the time without milliseconds
                start_time = full_start_time.split(',')[0]
                end_time = full_end_time.split(',')[0]
            except ValueError:
                # In a GUI, it's better to silently skip broken blocks
                # instead of filling the console with messages.
                print(f"Skipping block with malformed timeline: {block}")
                continue

            # Column 4: Character (blank cell)
            character = ''

            # Column 5: Dialogue
            dialogue_lines = lines[2:]
            raw_dialogue = ' '.join(line.strip() for line in dialogue_lines)
            dialogue = fix_html_tags(raw_dialogue)
            # Write the row to the CSV file
            csv_writer.writerow([start_time, '→', end_time, character, dialogue])

def convert_srt_to_docx(srt_path, docx_path, project_name, update_callback=None):
    """
    Converts an SRT subtitle file to a table in a DOCX file.
    """
    import docx
    from docx.shared import Cm, Pt
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    encoding = detect_encoding(srt_path)
    document = docx.Document()

    # --- Page and font configuration ---
    # Set left and right margins to 1 cm
    section = document.sections[0]
    section.left_margin = Cm(1)
    section.right_margin = Cm(1)

    # --- Footer ---
    footer = section.footer
    p = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    p.text = f"Generated by {PROGRAM_NAME}"
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Set the default font for the entire document to Arial
    style = document.styles['Normal']
    style.font.name = 'Arial'

    # --- Document Title ---
    if not project_name:
        project_name = "Subtitle Table" # Fallback if no name is provided
    title = document.add_heading(project_name, level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    # Ensure the title also uses Arial (level=0 uses the 'Title' style)
    title.style.font.name = 'Arial'

    with open(srt_path, 'r', encoding=encoding) as srt_file:
        content = srt_file.read()
    
    subtitle_blocks = re.split(r'\n\n+', remove_invalid_xml_chars(content).strip())

    # --- Table Creation ---
    header = ['Timecode', 'Character', 'Dialogue']
    table = document.add_table(rows=1, cols=len(header))


    hdr_cells = table.rows[0].cells
    for i, col_name in enumerate(header):
        cell = hdr_cells[i]
        # Clear the paragraph, add the text in a 'run' and make it bold
        cell.text = ''
        run = cell.paragraphs[0].add_run(col_name)
        run.bold = True
        # Center the paragraph containing the text
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        # Minimize paragraph spacing to reduce cell height
        p_format = cell.paragraphs[0].paragraph_format
        p_format.space_before = Pt(0)
        p_format.space_after = Pt(0)

    # --- Table Population ---
    for block in subtitle_blocks:
        lines = block.strip().split('\n')

        if len(lines) < 2:
            continue

        try:
            time_line = lines[1]
            full_start_time, full_end_time = time_line.split(' --> ')
            start_time = full_start_time.split(',')[0]
            end_time = full_end_time.split(',')[0]
            timecode = f"{start_time} → {end_time}"
        except:
            continue

        character = ''
        dialogue_lines = lines[2:]
        raw_dialogue = ' '.join(line.strip() for line in dialogue_lines)
        dialogue_with_tags = fix_html_tags(raw_dialogue)
        row_cells = table.add_row().cells

        # Column 1: Timecode (centered)
        row_cells[0].text = timecode
        row_cells[0].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        # Column 2: Character (centered)
        row_cells[1].text = character
        row_cells[1].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        # Column 3: Dialogue (with formatting)
        dialogo_paragraph = row_cells[2].paragraphs[0]
        add_formatted_text_to_paragraph(dialogo_paragraph, dialogue_with_tags)

        # Minimize spacing in all cells of the row
        for cell in row_cells:
            p_format = cell.paragraphs[0].paragraph_format
            p_format.space_before = Pt(0)
            p_format.space_after = Pt(0)

    document.save(docx_path)

def detect_encoding(file_path):
    """Detects the encoding of a file."""
    with open(file_path, 'rb') as f:
        raw_data = f.read()
    result = chardet.detect(raw_data)
    return result['encoding']

def remove_invalid_xml_chars(text):
    """Removes invalid XML control characters, preserving newlines and tabs."""
    # \n (newline), \r (carriage return), and \t (tab) are preserved,
    # which belong to the 'Cc' (Control) category but are valid and necessary.
    cleaned_text = ''.join(ch if unicodedata.category(ch) != 'Cc' or ch in ('\n', '\r', '\t') else '' for ch in text)
    return cleaned_text

def fix_html_tags(text):
    """
    Analyzes a text and closes any open HTML tags (i, b, u, font).
    Uses a stack to correctly handle nested tags.
    """
    # Regular expression to find opening and closing tags.
    # Group 1: '/' if it's a closing tag, '' if it's an opening tag.
    # Group 2: tag name.
    tags_regex = re.compile(r'<(/?)(\w+)[^>]*>')
    
    stack = []
    supported_tags = {'i', 'b', 'u', 'font'}

    for match in tags_regex.finditer(text):
        is_closing_tag = match.group(1) == '/'
        tag_name = match.group(2).lower()

        if tag_name not in supported_tags:
            continue

        if is_closing_tag:
            # It's a closing tag. If it matches the top of the stack, pop it.
            if stack and stack[-1] == tag_name:
                stack.pop()
        else:
            # It's an opening tag, add it to the stack.
            stack.append(tag_name)

    # At the end of the text, close all tags left on the stack, in reverse order (LIFO)
    corrected_text = text
    while stack:
        tag_to_close = stack.pop()
        corrected_text += f'</{tag_to_close}>'
        
    return corrected_text

def add_formatted_text_to_paragraph(paragraph, text_with_tags):
    """
    Parses text with HTML tags (<i>, <b>) and adds it to a
    python-docx paragraph with the corresponding formatting (italic, bold).
    The tags are removed from the final text.
    """
    paragraph.text = '' # Clear any previous content
    fragments = re.split(r'(<[^>]+>)', text_with_tags)
    
    is_italic = False
    is_bold = False

    for fragment in fragments:
        if not fragment:
            continue

        is_tag = fragment.startswith('<') and fragment.endswith('>')

        if is_tag:
            # It's a tag. Process it to change the formatting state.
            match = re.match(r'</?([a-zA-Z0-9]+)', fragment)
            if not match:
                continue # Malformed tag, ignore it

            tag_name = match.group(1).lower()
            is_closing_tag = fragment.startswith('</')

            if tag_name == 'i':
                is_italic = not is_closing_tag
            elif tag_name == 'b':
                is_bold = not is_closing_tag
        else:
            # It's not a tag, it's text. Add it with the current format.
            run = paragraph.add_run(fragment)
            run.italic = is_italic
            run.bold = is_bold

