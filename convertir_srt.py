def load_config():
    """Loads the configuration from the file."""
    if os.path.exists(config_file_path):
        config.read(config_file_path)
    else:
        # If the file doesn't exist, create an empty DEFAULT section
        config["DEFAULT"] = {}

def update_output_path():
    """Updates the suggested output path when the format changes."""
    current_input = input_path.get()
    if current_input:
        base_name = os.path.splitext(current_input)[0]
        new_extension = output_format.get()
        output_path.set(f"{base_name}.{new_extension}")

def browse_input_file():
    current_path = input_path.get()
    initial_dir = os.path.dirname(current_path) if current_path else "/"
    file_path = filedialog.askopenfilename(initialdir=initial_dir, title="Select SRT file", filetypes=(("Subtitle Files", "*.srt"), ("All files", "*.*")))
    if file_path:
        input_path.set(file_path)
        
        # Extract the base name of the file and use it as the project name
        base_name = os.path.basename(file_path)
        project_title = os.path.splitext(base_name)[0]
        project_name_var.set(project_title)

        update_output_path() # Suggest an output path
        status_label.config(text="Input file selected.")

def browse_output_file():
    out_format = output_format.get()
    if out_format == "csv":
        file_types = (("CSV Files", "*.csv"), ("All files", "*.*"))
    else: # docx
        file_types = (("Word Documents", "*.docx"), ("All files", "*.*"))

    current_path = output_path.get()
    initial_dir = os.path.dirname(current_path) if current_path else "/"
    initial_file = os.path.basename(current_path) if current_path else ""
    
    file_path = filedialog.asksaveasfilename(title="Guardar archivo como...", initialdir=initial_dir, initialfile=initial_file, defaultextension=f".{out_format}", filetypes=file_types)
    if file_path:
        output_path.set(file_path)
        status_label.config(text="Output path selected.")

